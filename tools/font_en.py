"""font_en.py: English pair glyphs (docs/re/text.md §English font).

Two English letters share one 12x14 game cell. A pair is a two-byte Shift-JIS-shaped code whose lead byte the game's
font never uses (FD2Font.FPK covers leads 81-83, 88-98 only), so it can't clash with a Japanese glyph:
    n = left * G + right            (left, right: indices into CHARS, G = len(CHARS))
    code = LEADS[n // 188], TRAILS[n % 188]
asm/font.asm decodes the same way (font lookup 0x8002C474 returns 0x8000 | n; the glyph decoder 0x8002C5EC draws
the two letters from the table this module writes to asm/font_data.inc).

    python -X utf8 tools/font_en.py inc          write asm/font_data.inc (build.py does this on every build)
    python -X utf8 tools/font_en.py sheet OUT.png [TEXT]   preview TEXT (default: every glyph) as the game would draw it
    python -X utf8 tools/font_en.py encode TEXT  text form -> bytes (hex)

In the text form (script/*.tsv `en`), printable ASCII and … ♪ ♥ become pair codes; tags ({n}, {wait}, {XX}...)
and Japanese characters (e.g. the name placeholder ＄＄＄＄＄＄) pass through. A run of odd length gets a trailing
space to fill its last cell."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "fonts" / "font6.txt"
INC = ROOT / "asm" / "font_data.inc"

CHARS = (" !\"%&'()*+,-./0123456789:;=?"
         "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz~…♪♥")
G = len(CHARS)
LEADS = [0x84, 0x85, 0x86, 0x87] + list(range(0x99, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = [t for t in range(0x40, 0xFD) if t != 0x7F]
assert len(TRAILS) == 188 and G * G <= len(LEADS) * len(TRAILS), (G, len(LEADS))
CELL_W, CELL_H, HALF = 12, 14, 6
TOP = 3          # font row 0 (cap top) lands on cell row 3; descenders reach row 12
INK = 3          # 2bpp value of ink (the Japanese font's solid value; palette 7FFF white)
TAG = re.compile(r"(\{[^{}]*\})")
FMT = re.compile(r"(\{[^{}]*\}|%s)")   # printf %s (rfd2 only) stays raw ASCII: sprintf reads it, not the font


def load_font(path=FONT):
    glyphs, name, rows = {}, None, []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# ") and name is None:     # header comments (pixel rows also start with '#')
            continue
        if line.startswith("== "):
            if name is not None:
                glyphs[name] = rows
            name, rows = line[3:], []
            name = " " if name == "space" else name
        elif name is not None and line:
            rows.append(line)
    glyphs[name] = rows
    return glyphs


def glyph_pixels(ch, font=None):
    """14 rows x 6 columns of 2bpp values for one letter."""
    rows = (font or load_font())[ch]
    assert len(rows) <= CELL_H - TOP, ch
    out = [[0] * HALF for _ in range(CELL_H)]
    for y, r in enumerate(rows):
        assert len(r) < HALF, f"{ch!r}: ink wider than {HALF - 1} px"
        for x, c in enumerate(r):
            if c == "#":
                out[TOP + y][x] = INK
    return out


def pair_code(a, b):
    n = CHARS.index(a) * G + CHARS.index(b)
    return bytes([LEADS[n // 188], TRAILS[n % 188]])


def decode_pair(code):
    """(left, right) for a pair code, else None."""
    if len(code) != 2 or code[0] not in LEADS or code[1] not in TRAILS:
        return None
    n = LEADS.index(code[0]) * 188 + TRAILS.index(code[1])
    return (CHARS[n // G], CHARS[n % G]) if n < G * G else None


def _run_tags(run):
    if len(run) % 2:
        run += " "
    return "".join("".join(f"{{{b:02X}}}" for b in pair_code(run[i], run[i + 1])) for i in range(0, len(run), 2))


def to_pairs(text):
    """Text form with English letters -> text form with pair codes as {XX} tags (jtext.encode turns them to bytes).
    Characters outside CHARS (Japanese, ＄ name placeholder, ￥) and printf %s are left as they are."""
    out = []
    for part in FMT.split(text):
        if FMT.fullmatch(part) or not part:
            out.append(part)
            continue
        run = ""
        for ch in part:
            if ch in CHARS:
                run += ch
            else:
                if run:
                    out.append(_run_tags(run))
                    run = ""
                out.append(ch)
        if run:
            out.append(_run_tags(run))
    return "".join(out)


def has_english(text):
    return any(ch in CHARS and ch != " " for part in TAG.split(text) if not TAG.fullmatch(part) for ch in part)


def write_inc(path=INC):
    font = load_font()
    lines = [f"; generated by tools/font_en.py from {FONT.name}: do not edit",
             f"; PAIR_G (= {G}) comes from the armips command line (build.patch_exe: -equ PAIR_G)",
             "pair_leadidx:"]
    idx = [0xFF] * 256
    for i, lead in enumerate(LEADS):
        idx[lead] = i
    for k in range(0, 256, 16):
        lines.append("    .byte " + ", ".join(f"0x{v:02X}" for v in idx[k:k + 16]))
    lines.append("pair_leads:      ; lead byte by index (n // 188), for asm/name.asm")
    lines.append("    .byte " + ", ".join(f"0x{v:02X}" for v in LEADS))
    lines.append(".align 4")
    lines.append("pair_glyphs:     ; per letter: 14 rows x 3 bytes (6 px 4bpp, low nibble = left pixel)")
    for ch in CHARS:
        px = glyph_pixels(ch, font)
        data = []
        for r in px:
            data += [r[x] | (r[x + 1] << 4) for x in range(0, HALF, 2)]
        lines.append(f"    .byte {', '.join(f'0x{v:02X}' for v in data)}   ; {ch!r}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def name_equs():
    """armips -equ values for asm/name.asm: CHARS indices of the full-width name-entry letters' ASCII forms."""
    return {"CH_SPACE": CHARS.index(" "), "CH_EXCL": CHARS.index("!"), "CH_QUES": CHARS.index("?"),
            "CH_0": CHARS.index("0"), "CH_UA": CHARS.index("A"), "CH_LA": CHARS.index("a")}


def name_to_pairs(sjis: bytes) -> bytes:
    """Python model of asm/name.asm name_commit: a full-width SJIS name (name entry) -> the stored name, with
    full-width Latin letters, digits, space, ! and ? turned into pair codes (an odd run gets a trailing space) and
    any other character kept. Stops at NUL or 12 bytes; the result is NUL-padded to 12 bytes."""
    full = {0x8140: " ", 0x8148: "?", 0x8149: "!"}
    full.update({0x8260 + i: chr(65 + i) for i in range(26)})
    full.update({0x8281 + i: chr(97 + i) for i in range(26)})
    full.update({0x824F + i: chr(48 + i) for i in range(10)})
    out, run = b"", ""
    for i in range(0, min(len(sjis), 12) - 1, 2):
        c = sjis[i] << 8 | sjis[i + 1]
        if sjis[i] == 0:
            break
        if c in full:
            run += full[c]
            if len(run) == 2:
                out += pair_code(*run)
                run = ""
            continue
        if run:
            out += pair_code(run, " ")
            run = ""
        out += sjis[i:i + 2]
    if run:
        out += pair_code(run, " ")
    return out.ljust(12, b"\0")


def sheet(out, text=None, zoom=4):
    from PIL import Image
    text = text if text is not None else CHARS
    if len(text) % 2:
        text += " "
    font = load_font()
    pal = [(24, 32, 72), (90, 90, 90), (190, 190, 190), (255, 255, 255)]
    cols = min(len(text) // 2, 26)
    nrows = (len(text) // 2 + cols - 1) // cols
    im = Image.new("RGB", (cols * CELL_W, nrows * CELL_H))
    for k in range(0, len(text), 2):
        cx, cy = (k // 2) % cols * CELL_W, (k // 2) // cols * CELL_H
        for half, ch in enumerate(text[k:k + 2]):
            for y, r in enumerate(glyph_pixels(ch, font)):
                for x, v in enumerate(r):
                    im.putpixel((cx + half * HALF + x, cy + y), pal[v])
    im.resize((im.width * zoom, im.height * zoom), Image.NEAREST).save(out)


def main(argv):
    if argv[0] == "inc":
        print(write_inc())
    elif argv[0] == "sheet":
        sheet(argv[1], argv[2] if len(argv) > 2 else None)
    elif argv[0] == "encode":
        sys.path.insert(0, str(ROOT / "tools"))
        import jtext
        print(jtext.encode(to_pairs(argv[1])).hex(" "))


if __name__ == "__main__":
    main(sys.argv[1:])
